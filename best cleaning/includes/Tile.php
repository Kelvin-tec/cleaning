    <p style="text-align: left;">
        <span>Step 1: Inspection</span><br>
        We assess your tile type, grout condition, stain types, and overall soil level.<br>
        <span>Step 2: Pre-Vacuum</span><br>
        We vacuum the entire area to remove loose dirt and debris.<br>
        <span>Step 3: Pre-Treatment</span><br>
        We apply a cleaning solution formulated for your tile type. For grout, we use an
        alkaline or pH-neutral cleaner depending on soil type.<br>
        <span>Step 4: Agitation</span><br>
        We work the solution into grout lines and tile edges using rotating brushes or hand tools.<br>
        <span>Step 5: High-Pressure Hot Water Extraction</span><br>
        We use truck-mounted or portable equipment to spray hot water (200°F+) at high pressure into
        grout lines and tile surfaces. A powerful vacuum extracts the water along with dissolved dirt.<br>
        <span>Step 6: Spot Treatment</span><br>
        Stubborn stains receive additional treatment.<br>
        <span>Step 7: Grout Drying</span><br>
        We use air movers to speed drying (2 to 4 hours for grout, longer for dense tile).<br>
        <span>Step 8: Sealing (Optional Add-On)</span><br>
        We apply a grout sealer that repels future stains and makes cleaning easier.
