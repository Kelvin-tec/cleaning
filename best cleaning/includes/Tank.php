        <span>Step 1: Assessment</span><br>
        We inspect the tank exterior and interior (where accessible) to assess sediment level,
        biofilm presence, and overall condition.<br>
        <span>Step 2: Water Drainage</span><br>
        We drain the tank. For large tanks, we may pump water to a nearby drain or use it for
        irrigation if safe.<br>
        <span>Step 3: Manual Scrubbing</span><br>
        We enter the tank (when safe) or use long-handled tools to scrub all interior
        surfaces walls, floor, ceiling, and baffles.<br>
        <span>Step 4: Sediment Removal</span><br>
        We remove accumulated sediment, scale, and debris using wet vacuums or manual removal.<br>
        <span>Step 5: High-Pressure Rinse</span><br>
        We rinse the tank interior with potable water to remove loosened debris<br>
        <span>Step 6: Disinfection</span><br>
        We apply a food-grade sanitizer (typically chlorine-based) to all interior surfaces.
        The solution sits for the required contact time to kill bacteria and biofilm.<br>
        <span>Step 7: Final Rinse</span><br>
        We rinse the tank thoroughly with potable water until chlorine levels return to
        safe drinking levels.<br>
        <span>Step 8: Refill and Testing</span><br>
        We refill the tank and take a water sample for bacterial testing.
